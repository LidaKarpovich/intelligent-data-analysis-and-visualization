    high = int(miss["crit"].isin(["Высокая", "Критическая"]).sum())
    a, av = dd.auc(lab["y"], lab["proba"]), dd.auc(lab_v["y"], lab_v["proba"])
    worst = mo.dropna(subset=["auc"]).sort_values("auc").iloc[0]
    jump = mo[mo["inc_rate"] > 2 * (cv.pos / cv.n)]
    first_jump = jump["month"].iloc[0] if len(jump) else None
