        f"TP {cv.tp} / FP {cv.fp} / FN {cv.fn} / TN {cv.tn}"
        + (" — ровно как в карточке модели." if meta.get("published_test_match") else " (с карточкой модели не совпало — проверьте данные)."),
        f"- **Эксплуатация** — {dd.fmt_date(p['oper'][0])} — {dd.fmt_date(p['oper'][1])}, карточки после окна обучения. "
        f"Модель оценила {dd.fmt_int(len(oper))} {pl(len(oper), ('карточку', 'карточки', 'карточек'))}, {dd.fmt_int(c.n)} из них аналитики закрыли вердиктом "
        "«Решён» или «False Positive» — по ним и сверяем.",
        "",
